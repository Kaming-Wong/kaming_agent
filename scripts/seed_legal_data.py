def main():
    print("=" * 50)
    print("法律知识库数据导入")
    print("=" * 50)

    client = MilvusClient()

    # 检查现有数据
    count = client.count("legal_docs")
    print(f"当前知识库文档数: {count}")

    if count > 0:
        confirm = input("知识库已有数据，是否追加? (y/n): ")
        if confirm.lower() != "y":
            print("已取消")
            return

    print(f"\n开始导入 {len(LEGAL_DOCS)} 条法律条文...")
    success = client.batch_insert_legal(LEGAL_DOCS)
    print(f"\n导入完成! 成功: {success} / 总计: {len(LEGAL_DOCS)}")

    final_count = client.count("legal_docs")
    print(f"知识库总文档数: {final_count}")


if __name__ == "__main__":
    main()
